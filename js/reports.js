/* =========================================================
   EMPLOYEE MANAGEMENT & PAYROLL SYSTEM
   FILE: js/reports.js

   PURPOSE:
   Secure reporting and export controller.

   SECURITY:
   - Firebase authenticated requests.
   - Backend-controlled report access.
   - No hardcoded records or statistics.
   - No client-side financial calculations.
   - No unrestricted employee data exports.
   - PDF/CSV generated by authorised backend.
========================================================= */

"use strict";

(() => {

    /* =====================================================
       01. CONFIGURATION
    ===================================================== */

    const CONFIG = Object.freeze({

        allowedRoles: [
            "super_admin",
            "hr_admin",
            "employee"
        ],

        pageSize: 10,

        searchDelay: 350,

        reportTypes: [
            "employees",
            "attendance",
            "leave",
            "payroll"
        ],

        endpoints: {

            access: "/reports/access",

            departments: "/reports/departments",

            summary: "/reports/summary",

            list: "/reports",

            export: "/reports/export"

        }

    });


    /* =====================================================
       02. APPLICATION STATE
    ===================================================== */

    const state = {

        initialized: false,

        context: null,

        permissions: {},

        reportType: "employees",

        records: [],

        columns: [],

        summary: [],

        totalRecords: 0,

        currentPage: 1,

        loading: false,

        exporting: false,

        requestSequence: 0,

        searchTimer: null,

        filters: {

            search: "",

            department: "",

            status: "",

            dateFrom: "",

            dateTo: ""

        }

    };


    /* =====================================================
       03. DOM UTILITIES
    ===================================================== */

    const get = (id) => {

        return document.getElementById(id);

    };


    const setText = (id, value) => {

        const element = get(id);

        if (element) {

            element.textContent = String(
                value ?? "—"
            );

        }

    };


    const setVisible = (id, visible) => {

        const element = get(id);

        if (element) {

            element.hidden = !visible;

        }

    };


    const create = (
        tag,
        value = "",
        className = ""
    ) => {

        const element = document.createElement(tag);

        element.textContent = String(value ?? "");

        if (className) {

            element.className = className;

        }

        return element;

    };


    const notify = (
        message,
        type = "success"
    ) => {

        window.EMSUI?.showToast(
            message,
            type
        );

    };


    /* =====================================================
       04. AUTHENTICATED REQUESTS
    ===================================================== */

    const request = async (
        endpoint,
        options = {}
    ) => {

        if (
            !window.EMSFirebase ||
            typeof window.EMSFirebase.request !== "function"
        ) {

            throw new Error(
                "Application data service is unavailable."
            );

        }

        return window.EMSFirebase.request(
            endpoint,
            options
        );

    };


    /* =====================================================
       05. PERMISSION MANAGEMENT
    ===================================================== */

    const hasPermission = (permission) => {

        return state.permissions[permission] === true;

    };


    const reportPermission = (type) => {

        const mappings = {

            employees: "viewEmployeeReports",

            attendance: "viewAttendanceReports",

            leave: "viewLeaveReports",

            payroll: "viewPayrollReports"

        };

        return mappings[type] || "";

    };


    const canViewReport = (type) => {

        return hasPermission(
            reportPermission(type)
        );

    };


    const applyPermissions = () => {

        document.querySelectorAll(
            "[data-report-permission]"
        ).forEach((element) => {

            const permission =
                element.dataset.reportPermission;

            element.hidden = !hasPermission(
                permission
            );

        });


        document.querySelectorAll(
            "[data-report-type]"
        ).forEach((element) => {

            const type =
                element.dataset.reportType;

            element.hidden = !canViewReport(type);

        });


        const exportCSV = get(
            "exportReportCSV"
        );

        const exportPDF = get(
            "exportReportPDF"
        );

        if (exportCSV) {

            exportCSV.hidden =
                !hasPermission("exportReports");

        }

        if (exportPDF) {

            exportPDF.hidden =
                !hasPermission("exportReports");

        }

    };


    const loadPermissions = async () => {

        /*
         * GET /reports/access
         *
         * Backend verifies the Firebase session
         * and returns published report permissions.
         *
         * Employee accounts must never gain access
         * to organisation-wide reports simply by
         * changing a URL or frontend variable.
         */

        const response = await request(
            CONFIG.endpoints.access
        );

        if (
            !response ||
            !response.permissions ||
            typeof response.permissions !== "object" ||
            Array.isArray(response.permissions)
        ) {

            throw new Error(
                "Report permission verification failed."
            );

        }

        const permissions = response.permissions;

        state.permissions = Object.freeze({

            viewEmployeeReports:
                permissions.viewEmployeeReports === true,

            viewAttendanceReports:
                permissions.viewAttendanceReports === true,

            viewLeaveReports:
                permissions.viewLeaveReports === true,

            viewPayrollReports:
                permissions.viewPayrollReports === true,

            exportReports:
                permissions.exportReports === true

        });

        applyPermissions();

    };


    /* =====================================================
       06. FORMATTING
    ===================================================== */

    const formatNumber = (value) => {

        if (
            value === null ||
            value === undefined ||
            value === ""
        ) {

            return "—";

        }

        const number = Number(value);

        return Number.isFinite(number)
            ? new Intl.NumberFormat("en-IN").format(number)
            : "—";

    };


    const formatCurrency = (value) => {

        if (
            value === null ||
            value === undefined ||
            value === ""
        ) {

            return "—";

        }

        const number = Number(value);

        if (!Number.isFinite(number)) {

            return "—";

        }

        return new Intl.NumberFormat(
            "en-IN",
            {

                style: "currency",

                currency: "INR",

                minimumFractionDigits: 2,

                maximumFractionDigits: 2

            }
        ).format(number);

    };


    const formatDate = (value) => {

        if (!value) {

            return "—";

        }

        /*
         * A date-only value is treated as a calendar
         * date, avoiding browser timezone shifts.
         */

        if (/^\d{4}-\d{2}-\d{2}$/.test(value)) {

            const [
                year,
                month,
                day
            ] = value.split("-").map(Number);

            const date = new Date(
                Date.UTC(year, month - 1, day)
            );

            if (
                date.getUTCFullYear() !== year ||
                date.getUTCMonth() !== month - 1 ||
                date.getUTCDate() !== day
            ) {

                return "—";

            }

            return new Intl.DateTimeFormat(
                "en-IN",
                {

                    day: "2-digit",

                    month: "short",

                    year: "numeric",

                    timeZone: "UTC"

                }
            ).format(date);

        }

        const date = new Date(value);

        if (Number.isNaN(date.getTime())) {

            return "—";

        }

        return new Intl.DateTimeFormat(
            "en-IN",
            {

                day: "2-digit",

                month: "short",

                year: "numeric"

            }
        ).format(date);

    };


    const formatPercentage = (value) => {

        if (
            value === null ||
            value === undefined ||
            value === ""
        ) {

            return "—";

        }

        const number = Number(value);

        return Number.isFinite(number)
            ? `${number.toFixed(1)}%`
            : "—";

    };


    const formatValue = (
        value,
        format = "text"
    ) => {

        switch (format) {

            case "number":

                return formatNumber(value);

            case "currency":

                return formatCurrency(value);

            case "date":

                return formatDate(value);

            case "percentage":

                return formatPercentage(value);

            default:

                if (
                    value === null ||
                    value === undefined ||
                    value === ""
                ) {

                    return "—";

                }

                return String(value);

        }

    };


    /* =====================================================
       07. REPORT TYPE VALIDATION
    ===================================================== */

    const isValidReportType = (type) => {

        return CONFIG.reportTypes.includes(type);

    };


    const selectInitialReport = () => {

        const requested =
            get("reportType")?.value || "";

        if (
            isValidReportType(requested) &&
            canViewReport(requested)
        ) {

            return requested;

        }

        return CONFIG.reportTypes.find(
            canViewReport
        ) || null;

    };


    /* =====================================================
       08. LOADING AND ERROR STATES
    ===================================================== */

    const setLoading = (loading) => {

        state.loading = loading;

        setVisible(
            "reportsLoading",
            loading
        );

        get("reportsTable")?.setAttribute(
            "aria-busy",
            String(loading)
        );

        const refreshButton = get(
            "refreshReports"
        );

        if (refreshButton) {

            refreshButton.disabled = loading;

        }

        updateExportButtons();

    };


    const showError = (message) => {

        const element = get(
            "reportsError"
        );

        if (element) {

            element.textContent = message;

            element.hidden = false;

        } else {

            notify(message, "danger");

        }

    };


    const clearError = () => {

        const element = get(
            "reportsError"
        );

        if (element) {

            element.textContent = "";

            element.hidden = true;

        }

    };


    const updateExportButtons = () => {

        const disabled = (

            state.loading ||
            state.exporting ||
            !hasPermission("exportReports") ||
            !canViewReport(state.reportType)

        );

        [

            "exportReportCSV",

            "exportReportPDF"

        ].forEach((id) => {

            const button = get(id);

            if (button) {

                button.disabled = disabled;

            }

        });

    };


    /* =====================================================
       09. DEPARTMENT FILTER OPTIONS
    ===================================================== */

    const loadDepartments = async () => {

        const select = get(
            "reportDepartmentFilter"
        );

        if (!select) {
            return;
        }

        try {

            /*
             * Backend returns only departments
             * permitted within the current scope.
             */

            const response = await request(
                CONFIG.endpoints.departments
            );

            if (
                !response ||
                !Array.isArray(response.items)
            ) {

                throw new Error(
                    "Department options unavailable."
                );

            }

            const previous = select.value;

            const fragment =
                document.createDocumentFragment();

            fragment.appendChild(

                new Option(
                    "All Departments",
                    ""
                )

            );

            response.items.forEach((department) => {

                if (
                    !department ||
                    typeof department.id !== "string" ||
                    !department.id.trim()
                ) {

                    return;

                }

                fragment.appendChild(

                    new Option(

                        String(
                            department.name ||
                            department.id
                        ),

                        department.id

                    )

                );

            });

            select.replaceChildren(fragment);

            if (
                Array.from(select.options).some(
                    (option) => {
                        return option.value === previous;
                    }
                )
            ) {

                select.value = previous;

            }

        } catch {

            select.replaceChildren(

                new Option(
                    "All Departments",
                    ""
                )

            );

            notify(
                "Unable to load department filters.",
                "warning"
            );

        }

    };


    /* =====================================================
       10. READ FILTERS
    ===================================================== */

    const readFilters = () => {

        state.filters.search =
            get("reportSearch")?.value.trim() || "";

        state.filters.department =
            get("reportDepartmentFilter")?.value || "";

        state.filters.status =
            get("reportStatusFilter")?.value || "";

        state.filters.dateFrom =
            get("reportDateFrom")?.value || "";

        state.filters.dateTo =
            get("reportDateTo")?.value || "";

    };


    const validDate = (value) => {

        if (!value) {
            return true;
        }

        if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {

            return false;

        }

        const [
            year,
            month,
            day
        ] = value.split("-").map(Number);

        const date = new Date(
            Date.UTC(year, month - 1, day)
        );

        return (
            date.getUTCFullYear() === year &&
            date.getUTCMonth() === month - 1 &&
            date.getUTCDate() === day
        );

    };


    const validateFilters = () => {

        const {
            dateFrom,
            dateTo
        } = state.filters;

        if (
            !validDate(dateFrom) ||
            !validDate(dateTo)
        ) {

            notify(
                "Enter valid report dates.",
                "warning"
            );

            return false;

        }

        if (
            dateFrom &&
            dateTo &&
            dateFrom > dateTo
        ) {

            notify(
                "Starting date cannot be later than ending date.",
                "warning"
            );

            return false;

        }

        return true;

    };


    const buildParameters = (
        includePagination = true
    ) => {

        const parameters = new URLSearchParams({

            type: state.reportType

        });

        if (includePagination) {

            parameters.set(
                "page",
                String(state.currentPage)
            );

            parameters.set(
                "limit",
                String(CONFIG.pageSize)
            );

        }

        Object.entries(state.filters).forEach(
            ([key, value]) => {

                if (value) {

                    parameters.set(
                        key,
                        value
                    );

                }

            }
        );

        return parameters;

    };


    const resetFilters = () => {

        [

            "reportSearch",

            "reportDepartmentFilter",

            "reportStatusFilter",

            "reportDateFrom",

            "reportDateTo"

        ].forEach((id) => {

            const element = get(id);

            if (element) {

                element.value = "";

            }

        });

        state.filters = {

            search: "",

            department: "",

            status: "",

            dateFrom: "",

            dateTo: ""

        };

        state.currentPage = 1;

        refresh();

    };


    /* =====================================================
       11. REPORT SUMMARY
    ===================================================== */

    const renderSummary = (items) => {

        const container = get(
            "reportsSummary"
        );

        if (!container) {
            return;
        }

        container.replaceChildren();

        if (
            !Array.isArray(items) ||
            items.length === 0
        ) {

            container.appendChild(

                create(
                    "p",
                    "No summary information available.",
                    "text-muted"
                )

            );

            return;

        }

        const fragment =
            document.createDocumentFragment();

        items.forEach((item) => {

            if (
                !item ||
                typeof item !== "object"
            ) {

                return;

            }

            const card = create(
                "div",
                "",
                "card"
            );

            const label = create(

                "p",

                item.label || "Summary",

                "text-muted"

            );

            const value = create(

                "strong",

                formatValue(
                    item.value,
                    item.format
                ),

                "report-summary-value"

            );

            card.append(
                label,
                value
            );

            fragment.appendChild(card);

        });

        container.appendChild(fragment);

    };


    const loadSummary = async () => {

        try {

            const parameters =
                buildParameters(false);

            const response = await request(

                `${CONFIG.endpoints.summary}?${parameters}`

            );

            if (
                !response ||
                !Array.isArray(response.items)
            ) {

                throw new Error(
                    "Invalid report summary."
                );

            }

            state.summary = response.items;

            renderSummary(response.items);

        } catch {

            state.summary = [];

            renderSummary([]);

        }

    };


    /* =====================================================
       12. REPORT COLUMNS
    ===================================================== */

    /*
     * Each report has a fixed, reviewed frontend
     * column schema.
     *
     * The backend must independently restrict
     * report fields based on actual permissions.
     *
     * A client requesting a different report type
     * must never bypass backend authorization.
     */

    const COLUMN_SCHEMAS = Object.freeze({

        employees: [

            {
                key: "employeeCode",
                label: "Employee ID"
            },

            {
                key: "employeeName",
                label: "Employee"
            },

            {
                key: "department",
                label: "Department"
            },

            {
                key: "designation",
                label: "Designation"
            },

            {
                key: "joiningDate",
                label: "Joining Date",
                format: "date"
            },

            {
                key: "status",
                label: "Status"
            }

        ],

        attendance: [

            {
                key: "date",
                label: "Date",
                format: "date"
            },

            {
                key: "employeeCode",
                label: "Employee ID"
            },

            {
                key: "employeeName",
                label: "Employee"
            },

            {
                key: "department",
                label: "Department"
            },

            {
                key: "checkIn",
                label: "Check In"
            },

            {
                key: "checkOut",
                label: "Check Out"
            },

            {
                key: "status",
                label: "Status"
            }

        ],

        leave: [

            {
                key: "employeeCode",
                label: "Employee ID"
            },

            {
                key: "employeeName",
                label: "Employee"
            },

            {
                key: "leaveType",
                label: "Leave Type"
            },

            {
                key: "startDate",
                label: "From",
                format: "date"
            },

            {
                key: "endDate",
                label: "To",
                format: "date"
            },

            {
                key: "totalDays",
                label: "Days",
                format: "number"
            },

            {
                key: "status",
                label: "Status"
            }

        ],

        payroll: [

            {
                key: "employeeCode",
                label: "Employee ID"
            },

            {
                key: "employeeName",
                label: "Employee"
            },

            {
                key: "period",
                label: "Period"
            },

            {
                key: "grossPay",
                label: "Gross Pay",
                format: "currency"
            },

            {
                key: "deductions",
                label: "Deductions",
                format: "currency"
            },

            {
                key: "netPay",
                label: "Net Pay",
                format: "currency"
            },

            {
                key: "status",
                label: "Status"
            }

        ]

    });


    /* =====================================================
       13. REPORT TABLE
    ===================================================== */

    const getTable = () => {

        return get("reportsTable");

    };


    const getTableHead = () => {

        return get("reportsTableHead") ||
            getTable()?.querySelector("thead");

    };


    const getTableBody = () => {

        return get("reportsTableBody") ||
            getTable()?.querySelector("tbody");

    };


    const renderTableHeaders = () => {

        const thead = getTableHead();

        if (!thead) {
            return;
        }

        const row = document.createElement("tr");

        state.columns.forEach((column) => {

            const heading = create(
                "th",
                column.label
            );

            heading.scope = "col";

            row.appendChild(heading);

        });

        thead.replaceChildren(row);

    };


    const renderEmpty = (message) => {

        const tbody = getTableBody();

        if (!tbody) {
            return;
        }

        const row = document.createElement("tr");

        const cell = create(
            "td",
            message
        );

        cell.colSpan = Math.max(
            1,
            state.columns.length
        );

        row.appendChild(cell);

        tbody.replaceChildren(row);

    };


    const renderRecords = () => {

        const tbody = getTableBody();

        if (!tbody) {
            return;
        }

        if (!state.records.length) {

            renderEmpty(
                "No report records found."
            );

            return;

        }

        const fragment =
            document.createDocumentFragment();

        state.records.forEach((record) => {

            const row = document.createElement("tr");

            state.columns.forEach((column) => {

                const value = formatValue(

                    record[column.key],

                    column.format

                );

                const cell = create(
                    "td",
                    value
                );

                cell.dataset.label = column.label;

                row.appendChild(cell);

            });

            fragment.appendChild(row);

        });

        tbody.replaceChildren(fragment);

        window.EMSUI?.refreshTableLabels(
            getTable()
        );

    };


    /* =====================================================
       14. PAGINATION
    ===================================================== */

    const renderPagination = () => {

        const totalPages = Math.max(

            1,

            Math.ceil(
                state.totalRecords / CONFIG.pageSize
            )

        );

        const start = state.totalRecords === 0
            ? 0
            : (
                (state.currentPage - 1) *
                CONFIG.pageSize
            ) + 1;

        const end = Math.min(

            state.currentPage * CONFIG.pageSize,

            state.totalRecords

        );

        setText(

            "reportsPaginationInfo",

            `${formatNumber(start)}–${formatNumber(end)} of ${formatNumber(state.totalRecords)}`

        );

        setText(

            "reportsCurrentPage",

            `${state.currentPage} / ${totalPages}`

        );

        const previous = get(
            "reportsPreviousPage"
        );

        const next = get(
            "reportsNextPage"
        );

        if (previous) {

            previous.disabled =
                state.loading ||
                state.currentPage <= 1;

        }

        if (next) {

            next.disabled =
                state.loading ||
                state.currentPage >= totalPages;

        }

    };


    const changePage = (direction) => {

        if (state.loading) {
            return;
        }

        const totalPages = Math.max(

            1,

            Math.ceil(
                state.totalRecords / CONFIG.pageSize
            )

        );

        const target =
            state.currentPage + direction;

        if (
            target < 1 ||
            target > totalPages
        ) {

            return;

        }

        state.currentPage = target;

        loadReport();

    };


    /* =====================================================
       15. FETCH REPORT RECORDS
    ===================================================== */

    const loadReport = async () => {

        if (!canViewReport(state.reportType)) {

            showError(
                "You do not have access to this report."
            );

            return;

        }

        if (!validateFilters()) {
            return;
        }

        const requestId =
            ++state.requestSequence;

        setLoading(true);

        clearError();

        try {

            /*
             * GET /reports?type=...
             *
             * Expected response:
             *
             * {
             *   items: [],
             *   total: number,
             *   page: number,
             *   limit: number
             * }
             *
             * Backend applies report-specific
             * authorization and record-level scope.
             */

            const response = await request(

                `${CONFIG.endpoints.list}?${buildParameters()}`

            );

            if (
                requestId !== state.requestSequence
            ) {

                return;

            }

            if (
                !response ||
                !Array.isArray(response.items) ||
                !Number.isSafeInteger(response.total) ||
                response.total < 0
            ) {

                throw new Error(
                    "Invalid report response."
                );

            }

            state.records = response.items;

            state.totalRecords = response.total;

            state.columns =
                COLUMN_SCHEMAS[state.reportType];

            renderTableHeaders();

            renderRecords();

            renderPagination();

            setVisible(
                "reportsContent",
                true
            );

        } catch {

            if (
                requestId !== state.requestSequence
            ) {

                return;

            }

            state.records = [];

            state.totalRecords = 0;

            renderEmpty(
                "Unable to load this report."
            );

            renderPagination();

            showError(
                "Report information could not be loaded."
            );

        } finally {

            if (
                requestId === state.requestSequence
            ) {

                setLoading(false);

                renderPagination();

            }

        }

    };


    /* =====================================================
       16. REPORT TYPE SELECTION
    ===================================================== */

    const changeReportType = async (type) => {

        if (
            !isValidReportType(type) ||
            !canViewReport(type)
        ) {

            notify(
                "This report is not available for your account.",
                "danger"
            );

            return;

        }

        state.reportType = type;

        state.currentPage = 1;

        state.records = [];

        state.totalRecords = 0;

        state.columns =
            COLUMN_SCHEMAS[type];

        const selector = get(
            "reportType"
        );

        if (selector) {

            selector.value = type;

        }

        document.querySelectorAll(
            "[data-report-type]"
        ).forEach((element) => {

            element.classList.toggle(

                "active",

                element.dataset.reportType === type

            );

        });

        renderTableHeaders();

        await refresh();

    };


    /* =====================================================
       17. SECURE EXPORT
    ===================================================== */

    const exportReport = async (format) => {

        if (
            state.exporting ||
            state.loading
        ) {

            return;

        }

        if (
            !["csv", "pdf"].includes(format)
        ) {

            return;

        }

        if (
            !hasPermission("exportReports") ||
            !canViewReport(state.reportType)
        ) {

            notify(
                "Report export is not authorised.",
                "danger"
            );

            return;

        }

        readFilters();

        if (!validateFilters()) {
            return;
        }

        state.exporting = true;

        updateExportButtons();

        try {

            /*
             * POST /reports/export
             *
             * Backend responsibilities:
             *
             * 1. Verify the authenticated Firebase UID.
             * 2. Verify permission for this report type.
             * 3. Reapply record and field restrictions.
             * 4. Apply filters to the full authorised
             *    dataset, not just the current page.
             * 5. Apply export-size and rate limits.
             * 6. Protect CSV against formula injection.
             * 7. Generate branded A4 PDF where requested.
             * 8. Record the export in the audit log.
             * 9. Return a short-lived download URL.
             *
             * Monetary figures and report totals must
             * originate from backend calculations.
             */

            const response = await request(

                CONFIG.endpoints.export,

                {

                    method: "POST",

                    body: {

                        type: state.reportType,

                        format,

                        filters: {
                            ...state.filters
                        }

                    }

                }

            );

            if (
                !response ||
                typeof response.url !== "string"
            ) {

                throw new Error(
                    "Report export is unavailable."
                );

            }

            const url = new URL(
                response.url
            );

            if (
                url.protocol !== "https:" ||
                url.username ||
                url.password
            ) {

                throw new Error(
                    "Invalid report download URL."
                );

            }

            /*
             * Open only the signed HTTPS URL
             * returned by the trusted backend.
             *
             * The frontend does not publish a report
             * directly to public storage.
             */

            const link = document.createElement("a");

            link.href = url.href;

            link.target = "_blank";

            link.rel = "noopener noreferrer";

            document.body.appendChild(link);

            link.click();

            link.remove();

            notify(
                "Report export generated successfully."
            );

        } catch {

            notify(
                "Unable to export this report.",
                "danger"
            );

        } finally {

            state.exporting = false;

            updateExportButtons();

        }

    };


    /* =====================================================
       18. REFRESH
    ===================================================== */

    const refresh = async () => {

        /*
         * Both requests are independently authorised.
         *
         * Failure in one section does not fabricate
         * data for the other.
         */

        await Promise.allSettled([

            loadReport(),

            loadSummary()

        ]);

    };


    /* =====================================================
       19. FILTER EVENTS
    ===================================================== */

    const initializeFilters = () => {

        get("reportSearch")?.addEventListener(
            "input",
            () => {

                window.clearTimeout(
                    state.searchTimer
                );

                state.searchTimer = window.setTimeout(
                    () => {

                        readFilters();

                        state.currentPage = 1;

                        refresh();

                    },
                    CONFIG.searchDelay
                );

            }
        );

        [

            "reportDepartmentFilter",

            "reportStatusFilter",

            "reportDateFrom",

            "reportDateTo"

        ].forEach((id) => {

            get(id)?.addEventListener(
                "change",
                () => {

                    readFilters();

                    state.currentPage = 1;

                    refresh();

                }
            );

        });

        get("resetReportFilters")?.addEventListener(
            "click",
            resetFilters
        );

    };


    /* =====================================================
       20. EVENT LISTENERS
    ===================================================== */

    const initializeEvents = () => {

        get("reportType")?.addEventListener(
            "change",
            (event) => {

                changeReportType(
                    event.target.value
                );

            }
        );

        document.querySelectorAll(
            "[data-report-type]"
        ).forEach((element) => {

            element.addEventListener(
                "click",
                () => {

                    changeReportType(
                        element.dataset.reportType
                    );

                }
            );

        });

        get("refreshReports")?.addEventListener(
            "click",
            refresh
        );

        get("reportsPreviousPage")?.addEventListener(
            "click",
            () => changePage(-1)
        );

        get("reportsNextPage")?.addEventListener(
            "click",
            () => changePage(1)
        );

        get("exportReportCSV")?.addEventListener(
            "click",
            () => exportReport("csv")
        );

        get("exportReportPDF")?.addEventListener(
            "click",
            () => exportReport("pdf")
        );

        initializeFilters();

    };


    /* =====================================================
       21. INITIALIZATION
    ===================================================== */

    const initialize = async () => {

        if (state.initialized) {
            return;
        }

        state.initialized = true;

        setLoading(true);

        setVisible(
            "reportsContent",
            false
        );

        try {

            if (!window.EMSFirebase) {

                throw new Error(
                    "Application service is unavailable."
                );

            }

            const context =
                await window.EMSFirebase.requireAuth(
                    CONFIG.allowedRoles
                );

            if (!context) {
                return;
            }

            state.context = context;

            await loadPermissions();

            const initialReport =
                selectInitialReport();

            if (!initialReport) {

                throw new Error(
                    "No reports are available for this account."
                );

            }

            state.reportType = initialReport;

            state.columns =
                COLUMN_SCHEMAS[initialReport];

            const selector = get(
                "reportType"
            );

            if (selector) {

                selector.value = initialReport;

                Array.from(selector.options)
                    .forEach((option) => {

                        if (
                            option.value &&
                            !canViewReport(option.value)
                        ) {

                            option.disabled = true;

                            option.hidden = true;

                        }

                    });

            }

            initializeEvents();

            await loadDepartments();

            readFilters();

            renderTableHeaders();

            await refresh();

        } catch {

            state.permissions = {};

            applyPermissions();

            setVisible(
                "reportsContent",
                false
            );

            showError(
                "Unable to verify reporting access."
            );

        } finally {

            setLoading(false);

        }

    };


    /* =====================================================
       22. PUBLIC MODULE INTERFACE
    ===================================================== */

    window.EMSReports = Object.freeze({

        initialize,

        refresh,

        changeReportType,

        exportCSV: () => exportReport("csv"),

        exportPDF: () => exportReport("pdf"),

        getContext: () => state.context

    });


    /* =====================================================
       23. START
    ===================================================== */

    const start = () => {

        if (
            document.body.dataset.page !== "reports"
        ) {

            return;

        }

        initialize();

    };


    if (
        document.readyState === "loading"
    ) {

        document.addEventListener(
            "DOMContentLoaded",
            start,
            {
                once: true
            }
        );

    } else {

        start();

    }

})();
